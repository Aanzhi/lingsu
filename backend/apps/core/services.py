def get_or_create_default_template(*, school, owner, category):
    normalized = category if category in DEFAULT_TEMPLATE_BLUEPRINTS else "research"
    name, stages = DEFAULT_TEMPLATE_BLUEPRINTS[normalized]
    existing = Template.objects.filter(school=school, category=normalized, is_published=True).first()
    if existing:
        # 蓝图演进（阶段数变化）时自动重建默认模板；已认领项目的任务链是独立副本，不受影响。
        if existing.stages.count() == len(stages):
            return existing
        existing.delete()
    template = Template.objects.create(
        school=school, owner=owner, category=normalized, name=name, is_published=True,
    )
    for order, (stage_name, task_name, description, material_title, report_section, guidance) in enumerate(stages, 1):
        stage = TemplateStage.objects.create(template=template, name=stage_name, order=order)
        task = TemplateTask.objects.create(stage=stage, name=task_name, description=description, order=1)
        TemplateMaterial.objects.create(
            task=task, title=material_title, required=True,
            submission_type="rich_text", report_section=report_section, order=order,
            guidance=guidance,
        )
    return template


def build_blank_reference(title, guidance):
    """Dynamically generate a blank reference template.

    Returns (content_bytes, filename). Prefers .docx via python-docx; falls back
    to a .md file when python-docx is unavailable, so no binary asset is shipped
    in migrations.
    """
    safe_title = (title or "参考范本").replace("/", "_")
    markdown = "\n".join([
        f"# {title or '参考范本'}",
        "",
        "## 填写指引",
        "",
        guidance or "",
        "",
        "## 内容大纲",
        "",
        "1. 背景与目标",
        "2. 过程记录",
        "3. 结果与证据",
        "4. 反思与改进",
        "",
        "---",
        "（本范本由系统根据模板指引自动生成，可下载后填写，再作为材料上传。）",
    ])
    try:
        from docx import Document
        doc = Document()
        doc.add_heading(title or "参考范本", level=1)
        doc.add_heading("填写指引", level=2)
        for para in (guidance or "").split("\n"):
            if para.strip():
                doc.add_paragraph(para)
        doc.add_heading("内容大纲", level=2)
        for item in ["背景与目标", "过程记录", "结果与证据", "反思与改进"]:
            doc.add_paragraph(item, style="ListNumber")
        buffer = BytesIO()
        doc.save(buffer)
        return buffer.getvalue(), f"{safe_title}_参考范本.docx"
    except Exception:
        return markdown.encode("utf-8"), f"{safe_title}_参考范本.md"
