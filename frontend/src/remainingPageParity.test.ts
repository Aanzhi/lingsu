    expect(studentProjects).toContain('eyebrow="项目" title="我的项目"')
    expect(studentProjects).toContain('class="current-project-panel paper-card"')
    expect(studentProjects).toContain('class="current-project-panel__identity"')
    expect(studentProjects).toContain('class="current-project-panel__content"')
