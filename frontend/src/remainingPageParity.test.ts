    expect(studentProjects).toContain('class="current-project-panel__actions"')
    expect(studentProjects).toContain('class="student-project-grid"')
    expect(studentProjects).toContain('class="student-project-card"')
    expect(studentProjects).toContain('const featuredProject = computed')
    expect(studentProjects).toContain('primary_teacher_name')
